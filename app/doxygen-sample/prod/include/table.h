/* NOTE: このヘッダーは多数のソース ファイルから参照されるため、            */
/*       @hideincludedbygraph によって "Included by" グラフを無効にします。 */

/**
 *  表を書く際、列セパレータ `|` の字下げは行わないようにします。
 *  (字下げが多いとプレーン テキストのコード ブロックとして解釈されるため)
 *
 *  | No. | 名称                | 備考                        |
 *  | --: | ------------------- | --------------------------- |
 *  |   1 | 名称1               |                             |
 *  |   2 | 名称2               |                             |
 *
 *  Table: 表のキャプション
 */
void table(void);

/**
 *  @brief          段落見出しの中に表題付きの表を書く例です。
 *
 *  par は空行で段落が終わります。
 *  表と Table: の間の空行を同じ見出しに残すため、parblock から endparblock までを使います。
 *
 *  @par            段落の中の表
 *  @parblock
 *  導入の文です。
 *
 *  | 項目 | 値 |
 *  | ------ | ---- |
 *  | A | 1 |
 *
 *  Table: 段落の中の表題
 *
 *  表の後の文も同じ見出しの中です。
 *  @endparblock
 */
void table_in_par(void);

/**
 *  @brief          箇条書きの後に表を書く例です。
 *
 *  対象の内訳です。
 *
 *  - 親項目です。
 *      - 子項目です。
 *  - 次の親項目です。
 *
 *  | 項目 | 値 |
 *  | ------ | ---- |
 *  | A | 1 |
 *
 *  Table: 本文と同じ桁の表題
 *
 *  表の後の文です。
 */
void table_after_shallow_list(void);

/**
 *  @brief          段落見出しの中で、箇条書きの後に表を書く例です。
 *
 *  箇条書きと表を同じ見出しに残すため、parblock から endparblock までを使います。
 *
 *  @par            箇条書きの後の表
 *  @parblock
 *  導入の文です。
 *
 *  - 親項目です。
 *      - 子項目です。
 *  - 次の親項目です。
 *
 *  | 項目 | 値 |
 *  | ------ | ---- |
 *  | A | 1 |
 *
 *  Table: 段落で箇条書きの後の表題
 *
 *  表の後の文も同じ見出しの中です。
 *  @endparblock
 */
void table_after_list_in_par(void);
